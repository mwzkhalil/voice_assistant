"""
Prometheus metrics for observability.

Histograms for latency, Counters for events, Gauges for current state.
All metrics are pre-registered at import time.
"""

from __future__ import annotations

from prometheus_client import Counter, Gauge, Histogram, Info

# --- Application Info ---

APP_INFO = Info(
    "voice_assistant",
    "Voice assistant application metadata",
)

# --- Call Metrics ---

CALLS_TOTAL = Counter(
    "voice_assistant_calls_total",
    "Total number of calls received",
    ["status"],  # answered, rejected, error
)

CALLS_ACTIVE = Gauge(
    "voice_assistant_calls_active",
    "Number of currently active calls",
)

CALL_DURATION_SECONDS = Histogram(
    "voice_assistant_call_duration_seconds",
    "Call duration in seconds",
    buckets=(1, 5, 10, 30, 60, 120, 300, 600),
)

# --- ASR Metrics ---

ASR_LATENCY_SECONDS = Histogram(
    "voice_assistant_asr_latency_seconds",
    "ASR inference latency in seconds",
    buckets=(0.05, 0.1, 0.25, 0.5, 1.0, 2.0, 5.0),
)

ASR_ERRORS_TOTAL = Counter(
    "voice_assistant_asr_errors_total",
    "Total ASR errors",
    ["error_type"],
)

ASR_CHUNKS_PROCESSED = Counter(
    "voice_assistant_asr_chunks_processed_total",
    "Total audio chunks processed by ASR",
)

# --- LLM Metrics ---

LLM_LATENCY_SECONDS = Histogram(
    "voice_assistant_llm_latency_seconds",
    "LLM time-to-first-token latency in seconds",
    buckets=(0.1, 0.25, 0.5, 1.0, 2.0, 5.0, 10.0),
)

LLM_TOTAL_LATENCY_SECONDS = Histogram(
    "voice_assistant_llm_total_latency_seconds",
    "LLM total generation latency in seconds",
    buckets=(0.5, 1.0, 2.0, 5.0, 10.0, 20.0, 30.0),
)

LLM_TOKENS_GENERATED = Counter(
    "voice_assistant_llm_tokens_generated_total",
    "Total tokens generated by LLM",
)

LLM_ERRORS_TOTAL = Counter(
    "voice_assistant_llm_errors_total",
    "Total LLM errors",
    ["error_type"],
)

LLM_CIRCUIT_BREAKER_STATE = Gauge(
    "voice_assistant_llm_circuit_breaker_state",
    "LLM circuit breaker state (0=closed, 1=open, 2=half-open)",
)

# --- TTS Metrics ---

TTS_LATENCY_SECONDS = Histogram(
    "voice_assistant_tts_latency_seconds",
    "TTS inference latency per chunk in seconds",
    buckets=(0.05, 0.1, 0.25, 0.5, 1.0, 2.0, 5.0),
)

TTS_ERRORS_TOTAL = Counter(
    "voice_assistant_tts_errors_total",
    "Total TTS errors",
    ["error_type"],
)

TTS_CHUNKS_GENERATED = Counter(
    "voice_assistant_tts_chunks_generated_total",
    "Total audio chunks generated by TTS",
)

# --- RTP Metrics ---

RTP_PACKETS_RECEIVED = Counter(
    "voice_assistant_rtp_packets_received_total",
    "Total RTP packets received",
)

RTP_PACKETS_SENT = Counter(
    "voice_assistant_rtp_packets_sent_total",
    "Total RTP packets sent",
)

RTP_PACKETS_DROPPED = Counter(
    "voice_assistant_rtp_packets_dropped_total",
    "Total RTP packets dropped",
    ["reason"],  # jitter, buffer_full, decode_error
)

# --- Pipeline Metrics ---

PIPELINE_E2E_LATENCY_SECONDS = Histogram(
    "voice_assistant_pipeline_e2e_latency_seconds",
    "End-to-end pipeline latency (speech end to first TTS audio out)",
    buckets=(0.5, 1.0, 1.5, 2.0, 3.0, 5.0, 10.0),
)

PIPELINE_INTERRUPTS_TOTAL = Counter(
    "voice_assistant_pipeline_interrupts_total",
    "Total barge-in interrupts",
)

# --- System Metrics ---

GPU_MEMORY_USED_BYTES = Gauge(
    "voice_assistant_gpu_memory_used_bytes",
    "GPU memory currently used in bytes",
)

GPU_MEMORY_TOTAL_BYTES = Gauge(
    "voice_assistant_gpu_memory_total_bytes",
    "GPU memory total in bytes",
)

REDIS_CONNECTIONS_ACTIVE = Gauge(
    "voice_assistant_redis_connections_active",
    "Active Redis connections",
)

# --- Timeout Metrics ---

TIMEOUTS_TOTAL = Counter(
    "voice_assistant_timeouts_total",
    "Total timeouts by component",
    ["component"],  # asr, llm, tts, ari, pipeline
)

# --- Error Counters ---

ERRORS_TOTAL = Counter(
    "voice_assistant_errors_total",
    "Total errors by category",
    ["category"],  # asr, llm, tts, ari, session, pipeline, system
)


class MetricsCollector:
    """
    Convenience facade for recording metrics.

    Provides typed methods to avoid metric label typos throughout the codebase.
    """

    @staticmethod
    def record_asr_latency(seconds: float) -> None:
        ASR_LATENCY_SECONDS.observe(seconds)

    @staticmethod
    def record_llm_ttft(seconds: float) -> None:
        LLM_LATENCY_SECONDS.observe(seconds)

    @staticmethod
    def record_llm_total(seconds: float) -> None:
        LLM_TOTAL_LATENCY_SECONDS.observe(seconds)

    @staticmethod
    def record_tts_latency(seconds: float) -> None:
        TTS_LATENCY_SECONDS.observe(seconds)

    @staticmethod
    def record_pipeline_e2e(seconds: float) -> None:
        PIPELINE_E2E_LATENCY_SECONDS.observe(seconds)

    @staticmethod
    def record_call_duration(seconds: float) -> None:
        CALL_DURATION_SECONDS.observe(seconds)

    @staticmethod
    def increment_call(status: str = "answered") -> None:
        CALLS_TOTAL.labels(status=status).inc()

    @staticmethod
    def set_active_calls(count: int) -> None:
        CALLS_ACTIVE.set(count)

    @staticmethod
    def increment_active_calls() -> None:
        CALLS_ACTIVE.inc()

    @staticmethod
    def decrement_active_calls() -> None:
        CALLS_ACTIVE.dec()

    @staticmethod
    def increment_asr_error(error_type: str) -> None:
        ASR_ERRORS_TOTAL.labels(error_type=error_type).inc()
        ERRORS_TOTAL.labels(category="asr").inc()

    @staticmethod
    def increment_llm_error(error_type: str) -> None:
        LLM_ERRORS_TOTAL.labels(error_type=error_type).inc()
        ERRORS_TOTAL.labels(category="llm").inc()

    @staticmethod
    def increment_tts_error(error_type: str) -> None:
        TTS_ERRORS_TOTAL.labels(error_type=error_type).inc()
        ERRORS_TOTAL.labels(category="tts").inc()

    @staticmethod
    def increment_timeout(component: str) -> None:
        TIMEOUTS_TOTAL.labels(component=component).inc()

    @staticmethod
    def increment_pipeline_interrupt() -> None:
        PIPELINE_INTERRUPTS_TOTAL.inc()

    @staticmethod
    def set_gpu_memory(used: int, total: int) -> None:
        GPU_MEMORY_USED_BYTES.set(used)
        GPU_MEMORY_TOTAL_BYTES.set(total)

    @staticmethod
    def set_redis_connections(count: int) -> None:
        REDIS_CONNECTIONS_ACTIVE.set(count)

    @staticmethod
    def set_circuit_breaker_state(state: int) -> None:
        LLM_CIRCUIT_BREAKER_STATE.set(state)
